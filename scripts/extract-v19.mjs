// Extract data and logic from FlyGuide_v19.html into src/.
//
//   node scripts/extract-v19.mjs          write src/data/*.js and assets/hero/*.webp
//   node scripts/extract-v19.mjs --check  verify src/ still matches v19 (no writes)
//
// Data is pulled out by parsing the v19 <script> blocks with acorn, evaluating
// each declaration in a Node VM and serialising the value back to source.
// Functions (scoreRules, buildKnowledgeBase) move as their original source text.
// Nothing is retyped.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import * as acorn from 'acorn';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const V19 = path.join(ROOT, 'FlyGuide_v19.html');
const CHECK = process.argv.includes('--check');

const html = fs.readFileSync(V19, 'utf8');

// ── 1. Script blocks ────────────────────────────────────────────
const scripts = [...html.matchAll(/<script>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
if (scripts.length !== 2) throw new Error('Expected 2 inline scripts in v19, found ' + scripts.length);

// Top-level declarations: name -> { kind, src, script }. Later definitions win
// (v19's second script overrides many functions from the first).
const decls = {};
const allDecls = []; // every definition, in order, for the report
scripts.forEach((code, si) => {
  const ast = acorn.parse(code, { ecmaVersion: 2022, sourceType: 'script' });
  for (const node of ast.body) {
    if (node.type === 'FunctionDeclaration') {
      const d = { name: node.id.name, kind: 'function', src: code.slice(node.start, node.end), script: si };
      decls[d.name] = d; allDecls.push(d);
    } else if (node.type === 'VariableDeclaration') {
      for (const v of node.declarations) {
        if (v.id.type !== 'Identifier') continue;
        const src = v.init ? code.slice(v.init.start, v.init.end) : 'undefined';
        const d = { name: v.id.name, kind: 'var', src, script: si };
        decls[d.name] = d; allDecls.push(d);
      }
    }
  }
});

// ── 2. Evaluate data declarations in a sandbox ──────────────────
function evalDecl(name) {
  const d = decls[name];
  if (!d || d.kind !== 'var') throw new Error('No var declaration for ' + name);
  const ctx = vm.createContext({});
  return vm.runInContext('(' + d.src + ')', ctx, { filename: 'v19:' + name });
}

// Serialise a value to JS source. Functions keep their original source text.
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
function ser(v, ind = '') {
  const next = ind + '  ';
  if (typeof v === 'function') return v.toString();
  if (v === null) return 'null';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  if (v === undefined) return 'undefined';
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== 'object' || x === null)) return '[' + v.map((x) => ser(x)).join(', ') + ']';
    return '[\n' + v.map((x) => next + ser(x, next)).join(',\n') + '\n' + ind + ']';
  }
  const keys = Object.keys(v);
  return '{\n' + keys.map((k) => next + (IDENT.test(k) ? k : JSON.stringify(k)) + ': ' + ser(v[k], next)).join(',\n') + '\n' + ind + '}';
}

// Structural fingerprint that includes function source, for round-trip checks.
function fp(v) {
  return JSON.stringify(v, (k, x) => (typeof x === 'function' ? 'ƒ' + x.toString() : x));
}

const HEADER = (names) => `// Generated by scripts/extract-v19.mjs from FlyGuide_v19.html. Do not edit by hand.\n// Contains: ${names.join(', ')}\n`;

const DATA_FILES = {
  'regions.js': ['REGIONS'],
  'rigs.js': ['RIGS', 'TIPPET_DATA', 'TIPPET_INFO'],
  'weather.js': ['WMO_CODES'],
  'chat.js': ['CHAT_SYSTEM_PROMPT'],
  'wiki.js': ['FLY_WIKI', 'SPECIES_WIKI'],
  'legal.js': ['LEGAL_CONTENT'],
  'notifications.js': ['NOTIFICATIONS'],
  'config.js': ['OWNER_EMAIL', 'STRIPE_KEY', 'STRIPE_MONTHLY_LINK', 'STRIPE_ANNUAL_LINK', 'FLYGUIDE_API_KEY', 'PREMIUM_REGIONS']
};
// Functions that move as source text, unchanged
const FUNCTION_FILES = {
  'knowledge.js': ['buildKnowledgeBase']
};

const outputs = {}; // relative path -> content
for (const [file, names] of Object.entries(DATA_FILES)) {
  let out = HEADER(names);
  for (const n of names) out += '\nvar ' + n + ' = ' + ser(evalDecl(n)) + ';\n';
  outputs['src/data/' + file] = out;
}
for (const [file, names] of Object.entries(FUNCTION_FILES)) {
  let out = HEADER(names);
  for (const n of names) {
    const d = decls[n];
    if (!d || d.kind !== 'function') throw new Error('Missing function ' + n);
    out += '\n' + d.src + '\n';
  }
  outputs['src/data/' + file] = out;
}

// Hero photos: decode the embedded WebP data URIs to files; build re-inlines the same bytes.
const hero = evalDecl('REGION_HERO_IMAGES');
const heroFiles = {};
for (const [k, uri] of Object.entries(hero)) {
  const m = /^data:image\/webp;base64,(.+)$/.exec(uri);
  if (!m) throw new Error('Unexpected hero image format for ' + k);
  heroFiles['assets/hero/' + k + '.webp'] = Buffer.from(m[1], 'base64');
}

// ── 3. Verify round trip ────────────────────────────────────────
const problems = [];
function evalFile(content) {
  const ctx = vm.createContext({});
  vm.runInContext(content, ctx);
  return ctx;
}
for (const [rel, content] of Object.entries(outputs)) {
  const file = path.basename(rel);
  const ctx = evalFile(content);
  for (const n of DATA_FILES[file] || []) {
    if (fp(ctx[n]) !== fp(evalDecl(n))) problems.push(`${rel}: ${n} differs from v19 after round trip`);
  }
  for (const n of FUNCTION_FILES[file] || []) {
    if (String(ctx[n]) !== decls[n].src) problems.push(`${rel}: ${n} source differs`);
  }
}
for (const [k, uri] of Object.entries(hero)) {
  const again = 'data:image/webp;base64,' + heroFiles['assets/hero/' + k + '.webp'].toString('base64');
  if (again !== uri) problems.push('hero ' + k + ' bytes differ');
}

// Content counts required by the brief
const REG = evalDecl('REGIONS');
const EXPECT = { dullstroom: 27, kzn: 20, ec: 19, cape: 17 };
const VENUE_VALS = {
  dullstroom: ['stillwater', 'laverpa', 'rainbow_valley', 'dullstroom_dam', 'river', 'spekboom'],
  kzn: ['bushmans', 'mooi', 'mkhomazi', 'lotheni', 'stillwater', 'kamberg', 'stream'],
  ec: ['sterkspruit', 'bell_kraai', 'langkloof', 'bokspruit', 'rhodes', 'farm_stream', 'barkly'],
  cape: ['smalblaar', 'elandspad', 'holsloot', 'dutoits', 'witte', 'general']
};
const counts = {};
for (const k of ['dullstroom', 'kzn', 'ec', 'cape']) {
  const R = REG[k];
  if (!R) { problems.push('Missing region ' + k); continue; }
  const flies = Object.keys(R.flies).length;
  counts[k] = { flies, venues: R.venues.length, venueVals: R.venueVals.length, venueInfo: R.venueInfo.length, hatch: R.hatch.length };
  if (flies !== EXPECT[k]) problems.push(`${k}: ${flies} flies, expected ${EXPECT[k]}`);
  if (R.venueInfo.length !== 4) problems.push(`${k}: ${R.venueInfo.length} venueInfo, expected 4`);
  if (R.hatch.length !== 12) problems.push(`${k}: ${R.hatch.length} hatch rows, expected 12`);
  if (R.venues.length !== R.venueVals.length) problems.push(`${k}: venues and venueVals lengths differ`);
  if (JSON.stringify(R.venueVals) !== JSON.stringify(VENUE_VALS[k])) problems.push(`${k}: venueVals ${JSON.stringify(R.venueVals)}`);
  for (const f of ['name', 'tag', 'sub', 'bestMonths', 'venues', 'venueVals', 'flies', 'venueInfo', 'hatch', 'scoreRules']) {
    if (!(f in R)) problems.push(`${k}: missing field ${f}`);
  }
  for (const [fk, fl] of Object.entries(R.flies)) {
    for (const f of ['name', 'sz', 'type', 'why', 'tip', 'when']) if (!(f in fl)) problems.push(`${k}.${fk}: missing ${f}`);
    if (!['dry', 'emerger', 'nymph', 'streamer', 'wet'].includes(fl.type)) problems.push(`${k}.${fk}: type ${fl.type}`);
  }
  for (const vi of R.venueInfo) for (const f of ['name', 'type', 'access', 'best', 'desc', 'flies']) if (!(f in vi)) problems.push(`${k} venueInfo missing ${f}`);
  for (const h of R.hatch) {
    for (const f of ['m', 'r', 'flies', 'note']) if (!(f in h)) problems.push(`${k} hatch missing ${f}`);
    if (!['prime', 'good', 'tech', 'wd'].includes(h.r)) problems.push(`${k} hatch rating ${h.r}`);
  }
}
const nRigs = Object.keys(evalDecl('RIGS')).length;
if (nRigs !== 16) problems.push(`RIGS has ${nRigs}, expected 16`);
const nFlyWiki = Object.keys(evalDecl('FLY_WIKI')).length;
if (nFlyWiki !== 49) problems.push(`FLY_WIKI has ${nFlyWiki}, expected 49`);
const nSpecies = Object.keys(evalDecl('SPECIES_WIKI')).length;
if (nSpecies !== 10) problems.push(`SPECIES_WIKI has ${nSpecies}, expected 10`);
const nNotif = evalDecl('NOTIFICATIONS').length;
if (nNotif !== 10) problems.push(`NOTIFICATIONS has ${nNotif}, expected 10`);

// ── 4. Logic that must stay identical to v19 ────────────────────
// These functions are copied into src/js/core/*.js verbatim. --check confirms
// they still match the last v19 definition (whitespace-insensitive).
const VERBATIM = [
  'getCtx', 'setPress', 'getMoonPhase', 'wmoToWeather', 'wmoToWind', 'pressureToApp', 'getTempSeason', 'getTimeOfDay',
  'fetchWeather', 'applyWeather', 'setStars', 'saveEntry', 'starsHtml', 'renderLog', 'exportCSV', 'showCompare', 'renderStatsBase',
  'loadUser', 'saveUser', 'isProUser', 'trialDaysLeft', 'showAuthError', 'handleLogin', 'handleSignup', 'continueAsGuest',
  'forgotPassword', 'simulateStripePayment', 'showPlanScreen', 'checkStripeReturn', 'initAuth',
  'persistUserRecord', 'afterAuth', 'confirmPlan', 'selectPlan', 'setBilling', 'closePlanScreen', 'doLogout',
  'buildRig', 'calcTippet', 'primeRanges', 'flyCard', 'recommend', 'printCard', 'buildFlybox', 'filterFlybox', 'buildHatch',
  'showThinking', 'hideThinking', 'hideSuggestions', 'sendSuggestion', 'sendChat', '_processImgQueue', 'makeFlyImg', 'makeSpeciesImg',
  'toggleKnow', 'showKnowSection', 'confirmSheet', 'deleteEntry', 'buildKnowledge', 'canUseRegion', 'setRegionIfAllowed', 'fishHere'
];
const norm = (s) => s.replace(/\/\/[^\n]*/g, '').replace(/\s+/g, '');

function srcFunctions() {
  const map = {};
  const dir = path.join(ROOT, 'src/js');
  const walk = (d) => fs.existsSync(d) && fs.readdirSync(d, { withFileTypes: true }).forEach((e) => {
    const p = path.join(d, e.name);
    if (e.isDirectory()) return walk(p);
    if (!p.endsWith('.js')) return;
    const code = fs.readFileSync(p, 'utf8');
    const ast = acorn.parse(code, { ecmaVersion: 2022, sourceType: 'script' });
    for (const n of ast.body) if (n.type === 'FunctionDeclaration') map[n.id.name] = { src: code.slice(n.start, n.end), file: path.relative(ROOT, p) };
  });
  walk(dir);
  return map;
}

const verbatimReport = [];
if (CHECK) {
  const have = srcFunctions();
  for (const n of VERBATIM) {
    if (!decls[n]) { problems.push('v19 has no function ' + n); continue; }
    if (!have[n]) { verbatimReport.push(`  - ${n}: not present in src (rewritten or renamed)`); continue; }
    const same = norm(have[n].src) === norm(decls[n].src);
    verbatimReport.push(`  ${same ? 'ok' : 'CHANGED'} ${n} (${have[n].file})`);
  }
  for (const [rel, content] of Object.entries(outputs)) {
    const p = path.join(ROOT, rel);
    if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== content) problems.push(rel + ' is missing or out of date; run npm run extract');
  }
  for (const [rel, buf] of Object.entries(heroFiles)) {
    const p = path.join(ROOT, rel);
    if (!fs.existsSync(p) || !fs.readFileSync(p).equals(buf)) problems.push(rel + ' is missing or out of date');
  }
} else {
  for (const [rel, content] of Object.entries(outputs)) {
    fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, rel), content);
  }
  for (const [rel, buf] of Object.entries(heroFiles)) {
    fs.mkdirSync(path.dirname(path.join(ROOT, rel)), { recursive: true });
    fs.writeFileSync(path.join(ROOT, rel), buf);
  }
}

console.log('v19 declarations:', allDecls.length, '(', Object.keys(decls).length, 'unique )');
console.log('Overridden in the v19 UI script:', allDecls.filter((d) => d.script === 0 && decls[d.name].script === 1).map((d) => d.name).join(', '));
console.log('Region counts:', JSON.stringify(counts));
console.log(`RIGS ${nRigs}, FLY_WIKI ${nFlyWiki}, SPECIES_WIKI ${nSpecies}, NOTIFICATIONS ${nNotif}`);
if (CHECK) { console.log('Verbatim logic check:'); console.log(verbatimReport.join('\n')); }
if (problems.length) { console.error('\nPROBLEMS:\n' + problems.map((p) => '  - ' + p).join('\n')); process.exit(1); }
console.log(CHECK ? 'Check passed.' : 'Extracted ' + Object.keys(outputs).length + ' data files and ' + Object.keys(heroFiles).length + ' hero photos.');
