// ── Imagery decode + LOD ─────────────────────────────────────
function decodeLayer(L){
  if (L.state === 'ready') return Promise.resolve(L);
  if (L.promise) return L.promise;
  L.state = 'loading';
  if (!L.el.getAttribute('src')) L.el.src = L.src;
  var p = (L.el.decode ? L.el.decode() : Promise.resolve()).catch(function(){
    // decode() can reject for off-DOM or throttled frames; fall back to the load event
    return new Promise(function(res){ if (L.el.complete) res(); else { L.el.onload = res; L.el.onerror = res; } });
  });
  L.promise = p.then(function(){ L.state = 'ready'; requestRender(); return L; });
  return L.promise;
}
function preloadRegion(k){
  var list = MAP.layers.filter(function(L){ return L.region === k; });
  return Promise.all(list.map(decodeLayer));
}
function updateLod(view){
  var s = MAP.cam.s;
  for (var i = 0; i < MAP.layers.length; i++){
    var L = MAP.layers[i], b = L.box;
    var need = L.z === 9 ? s >= MAP.fitS * 1.8 : s >= MAP.fitS * 4.5;
    var hits = b.x1 > view.x0 && b.x0 < view.x1 && b.y1 > view.y0 && b.y0 < view.y1;
    var want = need && hits;
    if (want && L.state !== 'ready'){ decodeLayer(L); continue; }
    if (want !== L.on){ L.on = want; L.el.classList.toggle('on', want); }
  }
}

// ── Camera ───────────────────────────────────────────────────
function measureMap(){ var st = document.getElementById('map-stage'); MAP.W = st.clientWidth; MAP.H = st.clientHeight; }
// pad: a number, or {t, r, b, l} to keep the framed box clear of the map chrome
function camFor(x0, y0, x1, y1, pad){
  var W = MAP.W || 600, H = MAP.H || 600;
  var P = typeof pad === 'number' ? { t: pad, r: pad, b: pad, l: pad } : pad;
  var s = Math.min((W - P.l - P.r) / (x1 - x0), (H - P.t - P.b) / (y1 - y0));
  // centre of the padded area, expressed as an offset from the stage centre
  var ox = (P.l - P.r) / 2, oy = (P.t - P.b) / 2;
  return { x: (x0 + x1) / 2 - ox / s, y: (y0 + y1) / 2 - oy / s, s: s };
}
function countryCam(){
  var a = proj([COUNTRY_FIT.lon0, COUNTRY_FIT.lat0]), b = proj([COUNTRY_FIT.lon1, COUNTRY_FIT.lat1]);
  var c = camFor(a[0], a[1], b[0], b[1], MAP.W < 640 ? 12 : 40);
  MAP.fitS = c.s; return c;
}
function regionCam(k){
  var m = REGION_META[k], xs = [], ys = [];
  m.venues.concat(m.towns).forEach(function(v){ var w = proj(v.p); xs.push(w[0]); ys.push(w[1]); });
  var x0 = Math.min.apply(null, xs), x1 = Math.max.apply(null, xs), y0 = Math.min.apply(null, ys), y1 = Math.max.apply(null, ys);
  var minSpan = 40; // about 0.4 degrees, so a tight region never over-zooms
  if (x1 - x0 < minSpan){ var cx = (x0 + x1) / 2; x0 = cx - minSpan / 2; x1 = cx + minSpan / 2; }
  if (y1 - y0 < minSpan){ var cy = (y0 + y1) / 2; y0 = cy - minSpan / 2; y1 = cy + minSpan / 2; }
  // phones: clear the breadcrumb (top), zoom controls (right) and scale bar and credits (bottom)
  return camFor(x0, y0, x1, y1, MAP.W < 640 ? { t: 84, r: 72, b: 64, l: 56 } : 96);
}
function clampCam(c){
  var b = MAP.base.box;
  c.s = Math.max(MAP.fitS * 0.8, Math.min(MAP.fitS * 60, c.s));
  c.x = Math.max(b.x0, Math.min(b.x1, c.x)); c.y = Math.max(b.y0, Math.min(b.y1, c.y));
  return c;
}

var renderQueued = false;
function requestRender(){ if (renderQueued) return; renderQueued = true; requestAnimationFrame(function(){ renderQueued = false; renderMap(); }); }
function renderMap(){
  var c = MAP.cam, W = MAP.W, H = MAP.H; if (!W) return;
  var tx = W / 2 - c.x * c.s, ty = H / 2 - c.y * c.s;
  var world = document.getElementById('map-world');
  world.style.transform = 'translate3d(' + tx.toFixed(2) + 'px,' + ty.toFixed(2) + 'px,0) scale(' + c.s.toFixed(5) + ')';
  var k = (1 / c.s).toFixed(5);
  if (k !== MAP.lastK){ MAP.lastK = k; world.style.setProperty('--k', k); }
  for (var i = 0; i < MAP.markers.length; i++){ var m = MAP.markers[i]; m.sx = m.x * c.s + tx; m.sy = m.y * c.s + ty; }
  if (MAP.mode !== 'country') declutterRegion(MAP.mode);
  for (i = 0; i < MAP.markers.length; i++){
    m = MAP.markers[i];
    m.el.style.transform = 'translate3d(' + (m.sx + m.ox).toFixed(1) + 'px,' + (m.sy + m.oy).toFixed(1) + 'px,0)';
  }
  if (MAP.mode === 'country') placeRegionChips(tx, ty);
  updateLod({ x0: c.x - W / 2 / c.s, x1: c.x + W / 2 / c.s, y0: c.y - H / 2 / c.s, y1: c.y + H / 2 / c.s });
  // Scale bar from the Mercator scale at the latitude in the middle of the view
  var mPerPx = 156543.03392 / 128 * Math.cos(unprojLat(c.y) * Math.PI / 180) / c.s;
  var pxPerKm = 1000 / mPerPx, opts = [5, 10, 20, 25, 50, 100, 200, 250, 500], km = 500;
  for (var j = 0; j < opts.length; j++){ if (opts[j] * pxPerKm >= 56){ km = opts[j]; break; } }
  document.getElementById('scale-bar').style.width = Math.round(km * pxPerKm) + 'px';
  document.getElementById('scale-txt').textContent = km + ' km';
  var stg = document.getElementById('map-stage'), zoomed = c.s > MAP.fitS * 1.15;
  if (stg.classList.contains('zoomed') !== zoomed) stg.classList.toggle('zoomed', zoomed);
}

// Region view: pins mark general areas, so when two would overlap on screen they
// are pushed apart a little (at most 26 px). Venue labels flip above their pin
// when they would cover another pin, and town labels step aside for pins.
function declutterRegion(k){
  var pins = [], towns = [];
  MAP.markers.forEach(function(m){ m.ox = 0; m.oy = 0; if (m.region === k){ if (m.kind === 'V') pins.push(m); else towns.push(m); } });
  var minD = 42, maxO = 26;
  for (var it = 0; it < 4; it++){
    for (var a = 0; a < pins.length; a++) for (var b = a + 1; b < pins.length; b++){
      var A = pins[a], B = pins[b], dx = (B.sx + B.ox) - (A.sx + A.ox), dy = (B.sy + B.oy) - (A.sy + A.oy), d = Math.hypot(dx, dy);
      if (d >= minD) continue;
      if (d < 0.01){ dx = 1; dy = 0; d = 1; }
      var push = (minD - d) / 2, ux = dx / d, uy = dy / d;
      A.ox -= ux * push; A.oy -= uy * push; B.ox += ux * push; B.oy += uy * push;
    }
    pins.forEach(function(p){ var o = Math.hypot(p.ox, p.oy); if (o > maxO){ p.ox *= maxO / o; p.oy *= maxO / o; } });
  }
  // label boxes (screen space)
  var boxes = pins.map(function(p){ return { x0: p.sx + p.ox - 20, y0: p.sy + p.oy - 20, x1: p.sx + p.ox + 20, y1: p.sy + p.oy + 20 }; });
  var hit = function(r, q){ return r.x0 < q.x1 && q.x0 < r.x1 && r.y0 < q.y1 && q.y0 < r.y1; };
  pins.forEach(function(p, i){
    var lab = p.el.querySelector('.v-label');
    if (p.lw === undefined || p.lw === 0) p.lw = lab.offsetWidth;
    if (!p.lw){ p.el.classList.remove('lbl-up'); return; }
    var cx = p.sx + p.ox, cy = p.sy + p.oy, w2 = p.lw / 2;
    var below = { x0: cx - w2, y0: cy + 22, x1: cx + w2, y1: cy + 44 }, above = { x0: cx - w2, y0: cy - 44, x1: cx + w2, y1: cy - 22 };
    var clash = function(r){ return boxes.some(function(q, j){ return j !== i && hit(r, q); }); };
    var up = clash(below) && !clash(above);
    if (p.el.classList.contains('lbl-up') !== up) p.el.classList.toggle('lbl-up', up);
    boxes.push(up ? above : below);
  });
  // the breadcrumb and zoom controls count as obstacles for town labels
  if (!chipCache) measureChips();
  var W = MAP.W, Z = chipCache._zoom, C = chipCache._crumb;
  boxes.push({ x0: W - 16 - Z.w - 4, y0: 0, x1: W, y1: 16 + Z.h + 4 }, { x0: 0, y0: 0, x1: 16 + C.w + 4, y1: 16 + C.h + 4 });
  towns.forEach(function(t){
    if (!t.tw) t.tw = t.el.firstChild.offsetWidth;
    var r = { x0: t.sx - 6, y0: t.sy - 9, x1: t.sx - 3 + t.tw + 4, y1: t.sy + 9 };
    var off = boxes.some(function(q){ return hit(r, q); });
    if (t.el.classList.contains('clash') !== off) t.el.classList.toggle('clash', off);
  });
}

// Region label chips: keep them inside the stage and clear of the breadcrumb and
// zoom controls, so no label is clipped at any width.
var chipCache = null;
function measureChips(){
  chipCache = {};
  var st = document.getElementById('map-stage'), z = st.querySelector('.zoom-ctl'), cr = document.getElementById('crumb');
  chipCache._zoom = { w: z.offsetWidth, h: z.offsetHeight };
  chipCache._crumb = { w: cr.offsetWidth, h: cr.offsetHeight };
  var small = MAP.W < 640;
  REGION_ORDER.forEach(function(k){
    var mk = document.querySelector('.mk[data-r="' + k + '"]'); if (!mk) return;
    var m = REGION_META[k], dir = small && m.dirSm ? m.dirSm : m.dir;
    ['up','down','left','right'].forEach(function(d){ mk.classList.toggle(d, d === dir); });
    var t = mk.querySelector('.mk-text');
    chipCache[k] = { w: t.offsetWidth, h: t.offsetHeight, el: t, dx: 0, dy: 0, dir: dir };
    t.style.setProperty('--lx', '0px'); t.style.setProperty('--ly', '0px');
  });
  chipCache._labels = [];
  MAP.markers.forEach(function(m){
    if (!m.el.classList.contains('mk-label')) return;
    var inner = m.el.firstChild; inner.style.setProperty('--lx', '0px');
    chipCache._labels.push({ m: m, el: inner, w: inner.offsetWidth, h: inner.offsetHeight, dx: 0 });
  });
}
function placeRegionChips(tx, ty){
  if (!chipCache) measureChips();
  var W = MAP.W, H = MAP.H, c = MAP.cam, g = 8, inset = 16, Z = chipCache._zoom, C = chipCache._crumb;
  REGION_ORDER.forEach(function(k){
    var ch = chipCache[k]; if (!ch || !ch.w) return;
    var w = proj(REGION_META[k].c), px = w[0] * c.s + tx, py = w[1] * c.s + ty, dir = ch.dir, L, T;
    if (dir === 'up'){ L = px - ch.w / 2; T = py - 20 - ch.h; }
    else if (dir === 'down'){ L = px - ch.w / 2; T = py + 20; }
    else if (dir === 'right'){ L = px + 20; T = py - ch.h / 2; }
    else { L = px - 20 - ch.w; T = py - ch.h / 2; }
    var dx = 0, dy = 0;
    if (T < inset + Z.h + g && L + ch.w > W - inset - Z.w - g) dx = (W - inset - Z.w - g) - (L + ch.w);
    if (T < inset + C.h + g && L + dx < inset + C.w + g) dx = (inset + C.w + g) - L;
    if (L + dx + ch.w > W - g) dx = W - g - ch.w - L;
    if (L + dx < g) dx = g - L;
    if (T < g) dy = g - T;
    if (T + ch.h > H - g) dy = H - g - ch.h - T;
    if (Math.abs(dx - ch.dx) > 0.4 || Math.abs(dy - ch.dy) > 0.4){
      ch.dx = dx; ch.dy = dy;
      ch.el.style.setProperty('--lx', dx.toFixed(1) + 'px'); ch.el.style.setProperty('--ly', dy.toFixed(1) + 'px');
    }
  });
  // Country labels: keep them inside the stage and clear of the zoom controls
  chipCache._labels.forEach(function(lb){
    if (!lb.w) return;
    var px = lb.m.x * c.s + tx, py = lb.m.y * c.s + ty, L = px - lb.w / 2, T = py - lb.h / 2, dx = 0;
    if (T < inset + Z.h + g && L + lb.w > W - inset - Z.w - g) dx = (W - inset - Z.w - g) - (L + lb.w);
    if (L + dx + lb.w > W - g) dx = W - g - lb.w - L;
    if (L + dx < g) dx = g - L;
    if (Math.abs(dx - lb.dx) > 0.4){ lb.dx = dx; lb.el.style.setProperty('--lx', dx.toFixed(1) + 'px'); }
  });
}

function flyTo(target, dur, done){
  if (MAP.anim){ cancelAnimationFrame(MAP.anim.raf); MAP.anim = null; }
  target = clampCam(target);
  if (REDUCE || !dur){ MAP.cam = target; renderMap(); if (done) done(); return; }
  var from = { x: MAP.cam.x, y: MAP.cam.y, s: MAP.cam.s }, t0 = performance.now();
  var inv0 = 1 / from.s, inv1 = 1 / target.s, zoomChange = Math.abs(inv0 - inv1) > 1e-9 && Math.abs(Math.log(target.s / from.s)) > 0.15;
  var a = { raf: 0, done: done };
  function step(now){
    var t = Math.min(1, (now - t0) / dur), e = EASE_IN_OUT(t);
    var s = from.s * Math.pow(target.s / from.s, e);
    // pan in proportion to the change in visible width, so the target stays steady on screen
    var k = zoomChange ? (inv0 - 1 / s) / (inv0 - inv1) : e;
    MAP.cam = { x: from.x + (target.x - from.x) * k, y: from.y + (target.y - from.y) * k, s: s };
    renderMap();
    if (t < 1) a.raf = requestAnimationFrame(step); else { MAP.anim = null; if (done) done(); }
  }
  a.raf = requestAnimationFrame(step); MAP.anim = a;
}
function stopFlight(){ if (MAP.anim){ var d = MAP.anim.done; cancelAnimationFrame(MAP.anim.raf); MAP.anim = null; if (d) d(); } }

function zoomAt(px, py, factor){
  stopFlight();
  var c = MAP.cam, W = MAP.W, H = MAP.H;
  var wx = (px - W / 2) / c.s + c.x, wy = (py - H / 2) / c.s + c.y;
  var s = Math.max(MAP.fitS * 0.8, Math.min(MAP.fitS * 60, c.s * factor));
  MAP.cam = clampCam({ x: wx - (px - W / 2) / s, y: wy - (py - H / 2) / s, s: s });
  requestRender();
}
function mapZoomBy(f){
  if (REDUCE) return zoomAt(MAP.W / 2, MAP.H / 2, f);
  var c = MAP.cam; flyTo({ x: c.x, y: c.y, s: c.s * f }, 320);
}
function mapRecenter(){ if (MAP.mode === 'country') flyTo(countryCam(), 600); else flyTo(regionCam(MAP.mode), 600); }

// ── Gestures ─────────────────────────────────────────────────
function bindMapGestures(){
  var st = document.getElementById('map-stage');
  var last = null, pinch = null, moved = 0, pending = null;
  // The stage clips its content; never let focus scroll it sideways (v19 bug)
  st.addEventListener('scroll', function(){ if (st.scrollLeft || st.scrollTop){ st.scrollLeft = 0; st.scrollTop = 0; } });
  function ids(){ return Object.keys(MAP.pointers); }
  st.addEventListener('pointerdown', function(e){
    if (e.target.closest('button,a')) return;
    if (ids().length >= 2) return;                      // ignore extra touches mid gesture
    var touchAtCountry = e.pointerType === 'touch' && !st.classList.contains('zoomed');
    MAP.pointers[e.pointerId] = { x: e.clientX, y: e.clientY };
    var n = ids().length;
    if (n === 1){ if (touchAtCountry) return; last = { x: e.clientX, y: e.clientY }; moved = 0; }
    if (n === 2){ var a = MAP.pointers[ids()[0]], b = MAP.pointers[ids()[1]]; pinch = { d: Math.hypot(a.x - b.x, a.y - b.y) || 1, s: MAP.cam.s }; last = null; }
    try { st.setPointerCapture(e.pointerId); } catch(err) {}
    stopFlight();
  });
  // Pointer moves are coalesced: the latest position is applied once per animation frame
  st.addEventListener('pointermove', function(e){
    if (!MAP.pointers[e.pointerId]) return;
    MAP.pointers[e.pointerId] = { x: e.clientX, y: e.clientY };
    if (pinch || last){ if (pinch) e.preventDefault(); if (!pending){ pending = requestAnimationFrame(applyMove); } }
  });
  function applyMove(){
    pending = null;
    var list = ids(), r = st.getBoundingClientRect();
    if (list.length === 2 && pinch){
      var a = MAP.pointers[list[0]], b = MAP.pointers[list[1]];
      var d = Math.hypot(a.x - b.x, a.y - b.y), target = pinch.s * d / pinch.d;
      zoomAt((a.x + b.x) / 2 - r.left, (a.y + b.y) / 2 - r.top, target / MAP.cam.s);
    } else if (last && list.length === 1){
      var p = MAP.pointers[list[0]], dx = p.x - last.x, dy = p.y - last.y; moved += Math.abs(dx) + Math.abs(dy);
      if (moved > 3) st.classList.add('dragging');
      MAP.cam = clampCam({ x: MAP.cam.x - dx / MAP.cam.s, y: MAP.cam.y - dy / MAP.cam.s, s: MAP.cam.s });
      last = { x: p.x, y: p.y }; renderMap();
    }
  }
  function end(e){
    if (!MAP.pointers[e.pointerId]) return;
    delete MAP.pointers[e.pointerId];
    var n = ids().length;
    if (n < 2) pinch = null;
    if (n === 1 && !(e.pointerType === 'touch' && !st.classList.contains('zoomed'))){ var p = MAP.pointers[ids()[0]]; last = { x: p.x, y: p.y }; }
    if (!n){ last = null; st.classList.remove('dragging'); }
  }
  st.addEventListener('pointerup', end); st.addEventListener('pointercancel', end);
  st.addEventListener('wheel', function(e){
    if (!(e.ctrlKey || e.metaKey)) return;   // plain scroll keeps scrolling the page
    e.preventDefault();
    var r = st.getBoundingClientRect();
    zoomAt(e.clientX - r.left, e.clientY - r.top, Math.exp(-e.deltaY * 0.0022));
  }, { passive: false });
  st.addEventListener('dblclick', function(e){ if (e.target.closest('button,a')) return; var r = st.getBoundingClientRect(); zoomAt(e.clientX - r.left, e.clientY - r.top, 1.8); });
}

