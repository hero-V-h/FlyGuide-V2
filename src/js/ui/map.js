// ─────────────────────────────────────────────────────────────
// SATELLITE MAP
// Web Mercator everywhere. World units are zoom 7 pixels (256 * 2^7 per world
// width), offset so the country image's top left corner is (0, 0); that keeps
// transform values small and precise.
//
//   world layer   <img> imagery (LOD) + <svg> borders, one composited transform
//   overlay       HTML markers, translate3d per frame, constant screen size
//   chrome        breadcrumb, zoom, scale bar, hint, attribution
//
// Camera {x, y, s}: screen = (world - cam) * s + viewport / 2
// MAP_DATA (images as data URIs, borders, origin) is generated by the build.
// ─────────────────────────────────────────────────────────────
var W7 = 256 * 128;
var MAP = { W: 0, H: 0, cam: { x: 0, y: 0, s: 0.4 }, fitS: 0.4, mode: 'country', venueSel: -1, markers: [], anim: null, pointers: {}, layers: [], base: null, preloaded: {} };

function mercX(lon){ return (lon + 180) / 360; }
function mercY(lat){ var p = lat * Math.PI / 180; return (1 - Math.log(Math.tan(p) + 1 / Math.cos(p)) / Math.PI) / 2; }
function proj(p){ return [mercX(p[0]) * W7 - MAP_DATA.origin.x, mercY(p[1]) * W7 - MAP_DATA.origin.y]; }
function unprojLat(y){ var n = Math.PI * (1 - 2 * (y + MAP_DATA.origin.y) / W7); return Math.atan(Math.sinh(n)) * 180 / Math.PI; }
function boxToWorld(b){ return { x0: b.x0 * W7 - MAP_DATA.origin.x, y0: b.y0 * W7 - MAP_DATA.origin.y, x1: b.x1 * W7 - MAP_DATA.origin.x, y1: b.y1 * W7 - MAP_DATA.origin.y }; }

